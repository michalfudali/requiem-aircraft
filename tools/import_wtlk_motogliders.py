def import_motogliders(db_path=None):
    with aircraft_store.transaction(db_path) as con:
        inserted = 0
        updated = 0
        for item in WTLK_MOTOGLIDERS:
            clean = validate_aircraft(item)
            existing = aircraft_store.fetch(con, clean['id'])
            if existing:
                aircraft_store.update(con, clean['id'], clean)
                updated += 1
            else:
                aircraft_store.insert(con, clean)
                inserted += 1
    print(f"Pomyślnie zaimportowano motogliders: {inserted} dodano, {updated} zaktualizowano.")


if __name__ == '__main__':
    import_motogliders()

